/// The shipped pipeline against the corpus, sample by sample, and the claim that
/// the tone rules are the *only* difference from the frozen pipeline.
///
/// **Tone rules only**: both sides of this comparison run with no text
/// normalizer, so the WeText numeral step cannot show up here as a "tone rule
/// change". That decomposition is what lets the table below be read as a claim
/// about one mechanism — `the_text_normalizer_changes_exactly_these_samples` is
/// the same test for the other one.
///
/// Asserted from both directions on purpose. A list of changed samples would pass
/// if a later change moved a *third* sample and rewrote the corpus; the other arm —
/// every sample not in the table has to come out identical under both settings — is
/// what makes the table a complete description of the difference rather than a
/// record of part of it. What the corpus *itself* is compared against is
/// `matches_the_javascript_pipeline_on_the_corpus`, one test up.
///
/// **The engine is on both sides here**, deliberately: the numeral step is no longer
/// a switch (there is no second reader behind it), and holding it fixed is what makes
/// this table a claim about the tone rules alone. The cost is `1,234`, which the
/// engine's reading newly brings into range of a tone rule — it is in the table
/// below, and in [`NUMERAL_READING_CHANGED`], for two different reasons.
#[test]
fn the_tone_rules_change_exactly_these_samples() {
    let Some(legacy) = legacy() else {
        return;
    };

    let samples = corpus().samples;
    let mut seen = 0;
    for sample in &samples {
        let shipped = legacy.phonemes(&sample.input, ToneRules::On, Some(&legacy.engine));
        let before = legacy.pre_tone_rules(&sample.input);

        match TONE_RULE_CHANGES
            .iter()
            .find(|(input, _)| *input == sample.input)
        {
            Some((_, expected)) => {
                seen += 1;
                assert_eq!(
                    shipped, *expected,
                    "{:?} under the tone rules",
                    sample.input
                );
                assert_ne!(
                    shipped, before,
                    "{:?} is in the table but did not move",
                    sample.input
                );
            }
            None => assert_eq!(
                shipped, before,
                "{:?} is not in the table but the tone rules moved it",
                sample.input
            ),
        }
    }

    // And the table does not describe samples the corpus does not have.
    assert_eq!(
        seen,
        TONE_RULE_CHANGES.len(),
        "every entry in the table is a corpus sample"
    );
}

/// The numeral step is a no-op on every corpus sample with nothing in it to read.
///
/// This used to be the mirror of [`TONE_RULE_CHANGES`] — "the numeral step moves
/// exactly these samples" — and it cannot be that any more: the samples it listed
/// are the five whose JavaScript reading a hand-written reader produced, and with
/// that reader deleted there is no engine-less side to compare against for them
/// (`tn::normalize` refuses a sentence with a digit in it and no engine). They are
/// in [`NUMERAL_READING_CHANGED`] now, with the values the engine reads them as,
/// and the claim that used to live here split in two:
///
/// - **for the samples with nothing for the engine in them, it changes nothing** —
///   asserted below, on both sides, over the whole corpus;
/// - **for the five that have something, it changes them and only them** —
///   `matches_the_javascript_pipeline_on_the_corpus`, which walks every sample.
///
/// The `None` arm is what makes this more than "the engine left these alone":
/// a sample that does not have a digit, a normalizable symbol or a full-width form
/// in it has to come out *identically* with and without the engine, which is the
/// property that lets `pre_tone_rules` be the corpus pipeline and not a guess.
#[test]
fn the_numeral_step_leaves_the_rest_of_the_corpus_alone() {
    let Some(phonemizer) = chinese_phonemizer() else {
        return;
    };
    let Some(legacy) = legacy() else {
        return;
    };

    let samples = corpus().samples;
    let mut checked = 0;
    for sample in &samples {
        if gate::drops_without_engine(&sample.input) {
            // One of the five, or a sample with something else for the engine in
            // it — either way `None` is not a state this pipeline can be in for
            // it, and the corpus test is where its reading is pinned.
            continue;
        }
        checked += 1;

        let shipped = phonemize(&phonemizer, &sample.input).phonemes;
        let without = legacy.phonemes(&sample.input, ToneRules::On, None);
        assert_eq!(
            shipped, without,
            "{:?} has nothing for the numeral step, but it moved it",
            sample.input
        );
    }

    // Twenty-five of the forty-seven. The other twenty-two have a digit, the
    // full-width `％`, a comma-grouped number or something else the engine maps to
    // a word — `gate::drops_without_engine` is the criterion, and this guard is
    // here so a corpus swap cannot quietly turn the test into a no-op.
    assert!(
        checked >= 20,
        "only {checked} samples were checked: the corpus is not the one this test is about"
    );
}

/// **The full-width fold, which for Chinese is a pipeline step.**
///
/// `full_to_half` is the wetext preprocessor English and Japanese run inside their
/// numeral step. Chinese cannot run it there: its numeral step comes *before* its
/// punctuation map, and the fold would rewrite `，` and `。` before the map owned
/// them (`mapPunctuation` turns both into `" . "`, which is the pause the listening
/// test chose). So Chinese's fold is `text::to_half_width`, called right after the
/// map — full-width letters and digits, and punctuation left to the map.
///
/// What it fixes is silence. `classify` accepts `A-Za-z` and nothing else, so a
/// full-width `Ａ` was `other`, `other` keeps punctuation only, and the character
/// disappeared: `ＡＢＣ` phonemized to the empty string.
#[test]
fn folds_full_width_latin_after_the_punctuation_map() {
    let Some(phonemizer) = chinese_phonemizer() else {
        return;
    };

    for (full, half, phonemes) in [
        ("ＡＢＣ", "ABC", "ə bˈiː sˈiː"),
        ("ｈｅｌｌｏ 世界", "hello 世界", "həlˈoʊ ʂɻ̩↘ʨje↘"),
        ("１２３", "123", "i↘pai↓ɚ↘ʂɻ̩↗ sa→n"),
    ] {
        for text in [full, half] {
            assert_eq!(
                phonemize(&phonemizer, text).phonemes,
                phonemes,
                "phonemizing {text:?}"
            );
        }
    }

    // And the map still owns the punctuation, which is the whole reason the fold is
    // second: a full-width comma is a period-length pause and not an ASCII comma.
    assert_eq!(
        phonemize(&phonemizer, "你好，世界。").phonemes,
        "ni↗xau↓. ʂɻ̩↘ʨje↘."
    );
    assert_eq!(
        phonemize(&phonemizer, "ＡＢＣ，你好。").phonemes,
        "ə bˈiː sˈiː. ni↗xau↓."
    );
}

#[test]
fn puts_one_space_between_words_and_none_inside_them() {
    let Some(phonemizer) = chinese_phonemizer() else {
        return;
    };

    // The user's report, and the reason jieba is in the pipeline at all: 人设
    // and 曾经 are each one word, and the model paused between their characters
    // when every syllable was separated. One word means one unit means no
    // boundary — so this is two spaces in the whole string, not five.
    let phonemes = phonemize(&phonemizer, "人设曾经").phonemes;
    assert_eq!(phonemes, "ɻə↗nʂɤ↘ ʦʰə↗ŋʨi→ŋ");
    assert_eq!(phonemes.matches(' ').count(), 1);

    // And the boundaries are jieba's, not a syllable count: 中华人民共和国 is
    // one word here, so the space after it is the only one in the first half.
    assert_eq!(
        phonemize(&phonemizer, "中华人民共和国武汉市长江大桥").phonemes,
        "ꭧʊ→ŋxwa↗ɻə↗nmi↗nkʊ↘ŋxɤ↗kwo↗ u↓xa↘nʂɻ̩↘ ꭧa↓ŋʨja→ŋta↘ʨʰjau↗"
    );
}

#[test]
fn a_latin_run_leaves_the_han_around_it_alone() {
    let Some(phonemizer) = chinese_phonemizer() else {
        return;
    };

    // The contract, and the property that survives the two sides using different
    // English engines: the runs are concatenated with nothing inserted, so the
    // whole is exactly its parts in order. Asserted by building the expected
    // string out of three separate calls rather than by writing it down, so the
    // test says "the Han is unaffected" rather than pinning whatever the English
    // engine happened to produce this month.
    let mixed = phonemize(&phonemizer, "你好ABC世界").phonemes;
    let expected = format!(
        "{}{}{}",
        phonemize(&phonemizer, "你好").phonemes,
        phonemize(&phonemizer, "ABC").phonemes,
        phonemize(&phonemizer, "世界").phonemes
    );
    assert_eq!(mixed, expected);

    // The Latin part really is the English engine's, and not the letters passed
    // through: an initialism is spelled out, and the schwa for `A` is CMU Dict's
    // entry for the letter — which is what `en_g2p.rs` pins as the English
    // engine's answer, and what espeak would have answered differently.
    assert_eq!(phonemize(&phonemizer, "ABC").phonemes, "ə bˈiː sˈiː");

    // A mixed-case word is read as a word, not spelled.
    assert!(phonemize(&phonemizer, "Hello世界")
        .phonemes
        .starts_with("həlˈoʊ"));
}

#[test]
fn a_numerals_reading_is_not_a_separate_run() {
    let Some(phonemizer) = chinese_phonemizer() else {
        return;
    };

    // The numeral has to become Han *before* the runs are split, or it would land
    // in an `other` run and be dropped as punctuation — unheard, and silently.
    // 只 is what makes this visible: as 三只 it is read with the numeral in one
    // word, and a split run would leave 三 missing and the word boundary wrong.
    // 我有 is two third tones in a row and the merge pass makes it one word, so
    // the shipped pipeline says *wó yǒu*: `wo↗jou↓` where the JavaScript said
    // `wo↓ jou↓`.
    assert_eq!(
        phonemize(&phonemizer, "我有3只猫").phonemes,
        "wo↗jou↓ sa→nꭧɻ̩→ mau→"
    );

    // And the reading itself, so a failure says which half broke.
    assert_eq!(phonemize(&phonemizer, "123").phonemes, "i↘pai↓ɚ↘ʂɻ̩↗ sa→n");
    assert_eq!(
        phonemize(&phonemizer, "123.45").phonemes,
        "i↘pai↓ɚ↘ʂɻ̩↗ sa→ntjɛ↓n sɹ̩↘u↓"
    );
}

#[test]
fn a_run_this_frontend_cannot_read_is_dropped_rather_than_read_wrong() {
    let Some(phonemizer) = chinese_phonemizer() else {
        return;
    };

    // Kana is `other` to `chinese.ts` — it has no kana alternative in its run
    // pattern — and `keepPunctuation` has no kana in its set, so it is dropped.
    // Reading it with the Chinese syllable table would be worse than dropping it,
    // which is why the Chinese pipeline has no kana run at all.
    //
    // **Dropping it also costs the word boundary**, and that is not a bug in
    // either implementation: 你好 and 世界 are two Han runs with an unreadable run
    // between them, and jieba segments each run on its own — so the space that
    // `你好世界` gets from being one two-word run does not appear. Asserted as the
    // concatenation rather than as the fixed string so the test says which
    // property is being checked, and pinned against the JavaScript by the corpus.
    assert_eq!(
        phonemize(&phonemizer, "你好あ世界").phonemes,
        format!(
            "{}{}",
            phonemize(&phonemizer, "你好").phonemes,
            phonemize(&phonemizer, "世界").phonemes
        )
    );
}

