/**
 * Transcribe HeadTTS's English letter-to-sound rules into Rust.
 *
 * The input is `crates/phonemize/tests/fixtures/headtts-en-parity.json`, which
 * `scripts/headtts-parity.mjs` dumps from an upstream HeadTTS checkout. This
 * script is a transcription and nothing more: it does not parse the JavaScript
 * source, does not re-derive the operator table (`#` = a vowel run, `%` = one of
 * ER/E/ES/ED/ING/ELY, and so on) and does not touch the ARPAbet table. Upstream's
 * own constructor already expanded all of that into a regular expression, a
 * match length and a phoneme string, and those three fields are what the Rust
 * engine runs — so the port cannot disagree with upstream about what an operator
 * means, only about how a regex matches, which is what `tests/headtts_en.rs`
 * pins.
 *
 * Regenerate with:
 *
 *     node scripts/gen-headtts-rules.mjs
 *
 * `--check` regenerates in memory and compares against the committed file
 * without writing anything, which is what CI runs — the same shape as
 * `gen-kokoro-vocab.mjs` and `gen-pinyin-pro-data.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const SOURCE = join(ROOT, 'crates', 'phonemize', 'tests', 'fixtures', 'headtts-en-parity.json');
const OUT = join(ROOT, 'crates', 'phonemize', 'src', 'backends', 'headtts_en', 'rules.rs');

/** A Rust string literal, with the two characters that cannot appear raw. */
function literal(text) {
  return `"${text.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

/** The characters of a Rust byte-string literal's content, for the header. */
function generate(fixture) {
  const groups = new Map();
  for (const [letter, regex, advance, phonemes] of fixture.rules) {
    if (!groups.has(letter)) groups.set(letter, []);
    groups.get(letter).push({ regex, advance, phonemes });
  }

  const lines = [];
  lines.push('//! HeadTTS\'s English letter-to-sound rules, transcribed.');
  lines.push('//!');
  lines.push('//! Generated by `scripts/gen-headtts-rules.mjs` from');
  lines.push('//! `crates/phonemize/tests/fixtures/headtts-en-parity.json` — **do not edit.**');
  lines.push('//!');
  lines.push('//! The source is the rule table of HeadTTS (`@met4citizen/headtts`), which is an');
  lines.push('//! adaptation of the letter-to-sound rules of NRL Report 7948 (1976). The fixture');
  lines.push('//! holds what upstream\'s own constructor produced for each rule — a regular');
  lines.push('//! expression, the number of characters it consumes, and the phonemes it emits —');
  lines.push('//! so this file is a transcription and not a re-implementation. That provenance');
  lines.push('//! is:');
  lines.push('//!');
  lines.push(`//! - package   \`@met4citizen/headtts\` ${fixture.source.package}`);
  lines.push(`//! - module    \`${fixture.source.module}\``);
  lines.push(`//! - sha256    \`${fixture.source.sha256}\``);
  lines.push(`//! - revision  \`${fixture.source.revision}\``);
  lines.push('//! - licence   MIT, (c) 2025 Mika Suominen — see `LICENSE` beside this file');
  lines.push('//!');
  lines.push('//! # The four rules that cannot fire');
  lines.push('//!');
  lines.push('//! A covering pass over the fixture\'s 296 words reaches 305 of the');
  lines.push(
    `//! ${fixture.counts.rules} rules, and the four it does not are not gaps in the corpus:`,
  );
  lines.push('//! they are shadowed by an earlier rule in their own group, so no spelling of an');
  lines.push('//! English word can reach them. `E#12` (` [EVEN]`) loses to `[E]^%=IY`, which matches');
  lines.push('//! `eVE`; `E#20` (`#:[EMENT]`) loses to `[E]^%=IY`, which matches `eME`; `I#10`');
  lines.push('//! (`[IE]`) loses to `[I]%=IY`, whose `E` alternative is the same two characters;');
  lines.push('//! and `O#10` (`[O]^EN`) loses to `[O]^%=OW` for the same reason. They are kept');
  lines.push('//! because they are upstream\'s table and this file is a transcription of it —');
  lines.push('//! deleting them would make the port disagree with HeadTTS about which rule wins.');
  lines.push('');
  lines.push('use super::engine::Rule;');
  lines.push('');
  lines.push('/// Every rule, in the order upstream tests them within a group.');
  lines.push('///');
  lines.push('/// The groups are contiguous — every `A` rule, then every `B` rule — so');
  lines.push('/// [`group`] hands out a range of this array rather than a second copy of the');
  lines.push('/// data. Flat with a range rather than one slice per letter because a `const`');
  lines.push('/// cannot take a range of another `const` (const slicing is not stable).');
  lines.push('///');
  lines.push('/// `#[rustfmt::skip]` because one rule per line is the only readable shape for');
  lines.push('/// a table this size; rustfmt would spend five lines on each of the 309.');
  lines.push('#[rustfmt::skip]');
  lines.push('pub const RULES: &[Rule] = &[');

  let offset = 0;
  const ranges = [];
  for (const [letter, rules] of groups) {
    lines.push(`    // ${letter}`);
    for (const rule of rules) {
      lines.push(
        `    Rule { regex: ${literal(rule.regex)}, advance: ${rule.advance}, ` +
          `phonemes: ${literal(rule.phonemes)} },`,
      );
    }
    ranges.push(`'${letter}' => Some(&RULES[${offset}..${offset + rules.length}]),`);
    offset += rules.length;
  }
  lines.push('];');
  lines.push('');
  lines.push('/// The rules to try for the character at the current position.');
  lines.push('///');
  lines.push('/// `None` for anything outside `A`–`Z`, which upstream skips without consuming');
  lines.push('/// — the same answer, since a character with no group has no spelling either way.');
  lines.push("pub fn group(letter: char) -> Option<&'static [Rule]> {");
  lines.push('    match letter {');
  for (const range of ranges) {
    lines.push(`        ${range}`);
  }
  lines.push('        _ => None,');
  lines.push('    }');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const fixture = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const generated = generate(fixture);

  if (check) {
    let committed;
    try {
      committed = readFileSync(OUT, 'utf8');
    } catch {
      console.error(`${relative(ROOT, OUT)} is missing; run without --check`);
      process.exitCode = 1;
      return;
    }
    if (committed !== generated) {
      console.error(`${relative(ROOT, OUT)} is stale; run without --check`);
      process.exitCode = 1;
      return;
    }
    console.log(`${relative(ROOT, OUT)} is up to date (${fixture.rules.length} rules)`);
    return;
  }

  writeFileSync(OUT, generated);
  console.log(`${relative(ROOT, OUT)}: ${fixture.rules.length} rules`);
}

main();
