/**
 * Regenerate the two Kokoro vocabularies the Rust phonemizer validates against.
 *
 * The two models do not share a phoneme inventory: v1.0 keeps 115 characters and
 * v1.1-zh keeps 172, and each drops characters the other keeps. A character
 * outside the vocabulary is not an error the tokenizer reports — its normaliser
 * is a `Replace` with the empty string, so the phoneme is silently deleted and
 * the word is heard without it. That is the failure this gate exists to turn into
 * a message, and it has to be checked in Rust because the tokenizer is not there
 * to ask.
 *
 * The source is each model's `tokenizer.json` (`model.vocab`), read directly from
 * the model directories. Set the paths via environment variables:
 *
 *     KOKORO_V10_DIR=/path/to/kokoro-v1.0 \
 *     KOKORO_V11_DIR=/path/to/kokoro-v1.1-zh \
 *     node scripts/generate/gen-kokoro-vocab.mjs
 *
 * If the environment variables are not set, the script falls back to a frozen
 * snapshot at `tests/v0/kokoro-vocabs.json` (measured from the model
 * repositories). This allows CI and casual runs to work without needing the full
 * model repos.
 *
 * `--check` regenerates in memory and compares against the committed files
 * without writing anything, which is what CI or a reviewer wants.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '../..');
const DATA_DIR = join(ROOT, 'crates', 'phonemize', 'data');
const FALLBACK_SOURCE = join(ROOT, 'tests', 'v0', 'kokoro-vocabs.json');

const MODEL_DIRS = {
  'v1.0': process.env.KOKORO_V10_DIR,
  'v1.1-zh': process.env.KOKORO_V11_DIR,
};

/**
 * What each file must contain, checked rather than assumed.
 *
 * The counts are the measured vocabulary sizes, and the characters are the ones
 * the two inventories differ on: v1.1-zh's zhuyin and its tone digits, and the
 * four tone arrows plus the five IPA letters that only v1.0 has. A source that
 * lost one of them would otherwise produce a gate that passes everything.
 */
const EXPECTED = {
  'v1.0': {
    file: 'vocab-v1.txt',
    count: 115,
    has: ['↓', '→', '↗', '↘', 'ɚ', 'ɤ', 'ɥ', 'ɻ', 'ꭧ', ' ', '\u0303', 'ɡ'],
    hasNot: ['ㄅ', 'ㄭ', '1', '5', '/', 'R'],
  },
  'v1.1-zh': {
    file: 'vocab-v11-zh.txt',
    count: 172,
    has: ['ㄅ', 'ㄆ', 'ㄇ', 'ㄭ', '1', '2', '3', '4', '5', '/', 'R', ' ', '\u0303', 'ɡ'],
    hasNot: ['↓', '→', '↗', '↘', 'ɚ', 'ɤ', 'ɥ', 'ɻ', 'ꭧ'],
  },
};

const HEADER = `# Generated by scripts/generate/gen-kokoro-vocab.mjs from tests/v0/kokoro-vocabs.json — do not edit.
# One character per line. A character that is not printable on its own is written
# as U+XXXX, so that the space (U+0020) and the combining marks survive an editor
# that strips trailing whitespace.
`;

/**
 * One line per character: the character, then its code point as a comment.
 *
 * The escaped form is used for anything that does not render on its own — the
 * space, and the combining marks, which would otherwise attach themselves to the
 * line ending.
 */
function line(character) {
  const code = character.codePointAt(0);
  const hex = code.toString(16).toUpperCase().padStart(4, '0');
  // `\p{M}` is a combining mark: it renders by attaching to what precedes it, and
  // there is nothing before it on the line. `\p{C}` and the space are the rest.
  const standalone = !/[\p{M}\p{C}\p{Z}]/u.test(character);
  return `${standalone ? character : `U+${hex}`} # U+${hex}`;
}

/**
 * Read vocabulary from model's tokenizer.json, or fall back to frozen snapshot.
 */
function readVocabulary(model) {
  const modelDir = MODEL_DIRS[model];
  
  // Try reading directly from model directory if available
  if (modelDir) {
    try {
      const tokenizerPath = join(modelDir, 'tokenizer.json');
      const tokenizer = JSON.parse(readFileSync(tokenizerPath, 'utf8'));
      const vocab = tokenizer.model?.vocab;
      if (!vocab || typeof vocab !== 'object') {
        throw new Error(`${tokenizerPath} has no model.vocab`);
      }
      // Extract characters from vocab keys
      const characters = Object.keys(vocab);
      console.log(`Read ${characters.length} characters from ${tokenizerPath}`);
      return characters;
    } catch (error) {
      console.warn(`Could not read from ${modelDir}: ${error.message}`);
      console.warn('Falling back to frozen snapshot...');
    }
  }
  
  // Fall back to frozen snapshot
  const source = JSON.parse(readFileSync(FALLBACK_SOURCE, 'utf8'));
  const characters = source[model]?.chars;
  if (!Array.isArray(characters)) {
    throw new Error(`${FALLBACK_SOURCE} has no ${model}.chars — the measurement changed shape`);
  }
  return characters;
}

function vocabulary(model) {
  const characters = readVocabulary(model);

  const expected = EXPECTED[model];
  if (characters.length !== expected.count) {
    throw new Error(
      `${model} has ${characters.length} characters, expected ${expected.count}`
    );
  }
  // A duplicate would mean the file no longer says what the tokenizer has.
  if (new Set(characters).size !== characters.length) {
    throw new Error(`${model} has a repeated character`);
  }

  const set = new Set(characters);
  for (const character of expected.has) {
    if (!set.has(character)) {
      throw new Error(`${model} is missing ${JSON.stringify(character)} (U+${character.codePointAt(0).toString(16).toUpperCase()})`);
    }
  }
  for (const character of expected.hasNot) {
    if (set.has(character)) {
      throw new Error(`${model} unexpectedly has ${JSON.stringify(character)}`);
    }
  }

  // Sorted by code point, so the file's order is a property of the file rather
  // than of the JSON that produced it. The tokenizer's own order is an artefact
  // of how it was built and nothing depends on it.
  return `${HEADER}${[...characters]
    .sort((a, b) => a.codePointAt(0) - b.codePointAt(0))
    .map(line)
    .join('\n')}\n`;
}

function main() {
  const check = process.argv.includes('--check');
  if (!check) mkdirSync(DATA_DIR, { recursive: true });

  let failed = false;
  for (const model of Object.keys(EXPECTED)) {
    const { file } = EXPECTED[model];
    const path = join(DATA_DIR, file);
    const relative = `crates/phonemize/data/${file}`;
    const content = vocabulary(model);

    if (check) {
      let committed;
      try {
        committed = readFileSync(path, 'utf8');
      } catch {
        console.error(`${relative} is missing; run without --check`);
        failed = true;
        continue;
      }
      if (committed === content) {
        console.log(`${relative} is up to date (${model}, ${EXPECTED[model].count} characters)`);
      } else {
        console.error(`${relative} is stale; run without --check`);
        failed = true;
      }
      continue;
    }

    writeFileSync(path, content);
    console.log(`wrote ${relative} (${model}, ${EXPECTED[model].count} characters)`);
  }

  return failed ? 1 : 0;
}

process.exit(main());
